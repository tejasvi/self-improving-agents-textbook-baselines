import subprocess
import tempfile
import json
import os
from pathlib import Path


def tool_info():
    return {
        "name": "run_tests",
        "description": """Run differential tests between a solution and a brute-force reference.
Executes random test cases generated by a generator script, comparing outputs between the solution and brute-force reference.
Each test is run with a timeout to detect TLE. Returns 'ALL PASSED' (with details) or the first failing case with both outputs and timing info.
Additionally, runs a max-size input test to measure timing when provided.

Checker contract (if checker_path is provided):
  The checker receives three file paths as command-line arguments (argv[1], argv[2], argv[3]):
  - argv[1]: path to a temporary file containing the test input
  - argv[2]: path to a temporary file containing the solution output
  - argv[3]: path to a temporary file containing the brute-force output
  The checker must exit with code 0 if the solution output is valid, or non-zero if invalid.""",
        "input_schema": {
            "type": "object",
            "properties": {
                "solution_path": {
                    "type": "string",
                    "description": "Path to the solution.py file to test"
                },
                "brute_path": {
                    "type": "string",
                    "description": "Path to the brute.py file (reference implementation)"
                },
                "generator_path": {
                    "type": "string",
                    "description": "Path to the gen.py file (test case generator)"
                },
                "checker_path": {
                    "type": "string",
                    "description": "Path to the checker.py file (output validator). If not provided, outputs are compared exactly."
                },
                "num_iterations": {
                    "type": "integer",
                    "description": "Number of random test cases to run (default: 100)"
                },
                "timeout_sec": {
                    "type": "number",
                    "description": "Timeout in seconds per test case (default: 5.0)"
                },
                "max_input_path": {
                    "type": "string",
                    "description": "Optional path to a max-size input file for timing measurement"
                },
                "extra_inputs_dir": {
                    "type": "string",
                    "description": "Optional path to a directory containing regression test inputs. Files in this directory will be tested against both solution and brute-force."
                }
            },
            "required": ["solution_path", "brute_path", "generator_path"]
        }
    }


def tool_function(
    solution_path,
    brute_path,
    generator_path,
    checker_path=None,
    num_iterations=100,
    timeout_sec=5.0,
    max_input_path=None,
    extra_inputs_dir=None
):
    """
    Run differential tests between solution and brute-force reference.
    
    Returns a string with 'ALL PASSED' or failure details with both outputs and timing.
    
    If checker_path is provided, the checker is invoked with three file-path arguments.
    """
    try:
        solution_path = Path(solution_path)
        brute_path = Path(brute_path)
        generator_path = Path(generator_path)
        
        # Validate paths exist
        if not solution_path.exists():
            return f"Error: solution_path {solution_path} does not exist"
        if not brute_path.exists():
            return f"Error: brute_path {brute_path} does not exist"
        if not generator_path.exists():
            return f"Error: generator_path {generator_path} does not exist"
        
        if checker_path and not Path(checker_path).exists():
            return f"Error: checker_path {checker_path} does not exist"
        
        # Run random differential tests
        for test_num in range(num_iterations):
            try:
                # Generate test case
                gen_result = subprocess.run(
                    ["python3", str(generator_path)],
                    capture_output=True,
                    text=True,
                    timeout=timeout_sec
                )
                test_input = gen_result.stdout
                
                if gen_result.returncode != 0:
                    return f"Error in test case generation: {gen_result.stderr}"
                
                # Run solution
                sol_start = __import__('time').time()
                sol_result = subprocess.run(
                    ["python3", str(solution_path)],
                    input=test_input,
                    capture_output=True,
                    text=True,
                    timeout=timeout_sec
                )
                sol_time = __import__('time').time() - sol_start
                
                if sol_result.returncode != 0:
                    return (
                        f"Solution failed on test {test_num}:\n"
                        f"Input:\n{test_input}\n"
                        f"Error:\n{sol_result.stderr}"
                    )
                
                sol_output = sol_result.stdout.strip()
                
                # Run brute-force
                brute_start = __import__('time').time()
                brute_result = subprocess.run(
                    ["python3", str(brute_path)],
                    input=test_input,
                    capture_output=True,
                    text=True,
                    timeout=timeout_sec
                )
                brute_time = __import__('time').time() - brute_start
                
                if brute_result.returncode != 0:
                    return (
                        f"Brute-force failed on test {test_num}:\n"
                        f"Input:\n{test_input}\n"
                        f"Error:\n{brute_result.stderr}"
                    )
                
                brute_output = brute_result.stdout.strip()
                
                # Check outputs match
                if checker_path:
                    # Use checker with file paths as arguments
                    with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_input:
                        f_input.write(test_input)
                        input_file = f_input.name
                    
                    with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_sol:
                        f_sol.write(sol_output)
                        sol_file = f_sol.name
                    
                    with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_brute:
                        f_brute.write(brute_output)
                        brute_file = f_brute.name
                    
                    try:
                        check_result = subprocess.run(
                            ["python3", str(checker_path), input_file, sol_file, brute_file],
                            capture_output=True,
                            text=True,
                            timeout=timeout_sec
                        )
                        if check_result.returncode != 0:
                            return (
                                f"Test {test_num} failed (checker validation):\n"
                                f"Input:\n{test_input}\n"
                                f"Solution output:\n{sol_output}\n"
                                f"Brute-force output:\n{brute_output}\n"
                                f"Checker feedback:\n{check_result.stdout}\n"
                                f"Solution time: {sol_time:.3f}s, Brute time: {brute_time:.3f}s"
                            )
                    finally:
                        Path(input_file).unlink()
                        Path(sol_file).unlink()
                        Path(brute_file).unlink()
                else:
                    # Direct output comparison
                    if sol_output != brute_output:
                        return (
                            f"Test {test_num} failed (output mismatch):\n"
                            f"Input:\n{test_input}\n"
                            f"Expected output:\n{brute_output}\n"
                            f"Got output:\n{sol_output}\n"
                            f"Solution time: {sol_time:.3f}s, Brute time: {brute_time:.3f}s"
                        )
                
            except subprocess.TimeoutExpired:
                return (
                    f"Test {test_num} timed out (exceeded {timeout_sec}s):\n"
                    f"Input:\n{test_input}"
                )
            except Exception as e:
                return f"Error during test {test_num}: {str(e)}"
        
        # All random tests passed; check regression tests if provided
        result_msg = f"All {num_iterations} random tests passed!"
        
        if extra_inputs_dir:
            extra_inputs_path = Path(extra_inputs_dir)
            if extra_inputs_path.exists() and extra_inputs_path.is_dir():
                regression_files = sorted(extra_inputs_path.glob('*.txt'))
                for regression_file in regression_files:
                    try:
                        with open(regression_file, 'r') as f:
                            test_input = f.read()
                        
                        # Run solution
                        sol_result = subprocess.run(
                            ["python3", str(solution_path)],
                            input=test_input,
                            capture_output=True,
                            text=True,
                            timeout=timeout_sec
                        )
                        
                        if sol_result.returncode != 0:
                            return (
                                f"Solution failed on regression test {regression_file.name}:\n"
                                f"Input:\n{test_input}\n"
                                f"Error:\n{sol_result.stderr}"
                            )
                        
                        sol_output = sol_result.stdout.strip()
                        
                        # Run brute-force
                        brute_result = subprocess.run(
                            ["python3", str(brute_path)],
                            input=test_input,
                            capture_output=True,
                            text=True,
                            timeout=timeout_sec
                        )
                        
                        if brute_result.returncode != 0:
                            return (
                                f"Brute-force failed on regression test {regression_file.name}:\n"
                                f"Input:\n{test_input}\n"
                                f"Error:\n{brute_result.stderr}"
                            )
                        
                        brute_output = brute_result.stdout.strip()
                        
                        # Check outputs match
                        if checker_path:
                            with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_input:
                                f_input.write(test_input)
                                input_file = f_input.name
                            
                            with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_sol:
                                f_sol.write(sol_output)
                                sol_file = f_sol.name
                            
                            with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.txt') as f_brute:
                                f_brute.write(brute_output)
                                brute_file = f_brute.name
                            
                            try:
                                check_result = subprocess.run(
                                    ["python3", str(checker_path), input_file, sol_file, brute_file],
                                    capture_output=True,
                                    text=True,
                                    timeout=timeout_sec
                                )
                                if check_result.returncode != 0:
                                    return (
                                        f"Regression test {regression_file.name} failed (checker validation):\n"
                                        f"Input:\n{test_input}\n"
                                        f"Solution output:\n{sol_output}\n"
                                        f"Brute-force output:\n{brute_output}\n"
                                        f"Checker feedback:\n{check_result.stdout}"
                                    )
                            finally:
                                Path(input_file).unlink()
                                Path(sol_file).unlink()
                                Path(brute_file).unlink()
                        else:
                            if sol_output != brute_output:
                                return (
                                    f"Regression test {regression_file.name} failed (output mismatch):\n"
                                    f"Input:\n{test_input}\n"
                                    f"Expected output:\n{brute_output}\n"
                                    f"Got output:\n{sol_output}"
                                )
                    
                    except subprocess.TimeoutExpired:
                        return (
                            f"Regression test {regression_file.name} timed out (exceeded {timeout_sec}s):\n"
                            f"Input:\n{test_input}"
                        )
                    except Exception as e:
                        return f"Error during regression test {regression_file.name}: {str(e)}"
                
                result_msg += f" + {len(regression_files)} regression tests passed!"
        
        # Test maximum input size if provided
        if max_input_path and Path(max_input_path).exists():
            try:
                with open(max_input_path, 'r') as f:
                    max_input = f.read()
                
                max_start = __import__('time').time()
                max_result = subprocess.run(
                    ["python3", str(solution_path)],
                    input=max_input,
                    capture_output=True,
                    text=True,
                    timeout=timeout_sec * 3  # Allow more time for max input
                )
                max_time = __import__('time').time() - max_start
                
                if max_result.returncode != 0:
                    result_msg += f"\nMax input test FAILED:\n{max_result.stderr}"
                else:
                    result_msg += f"\nMax input test passed in {max_time:.3f}s"
            except subprocess.TimeoutExpired:
                result_msg += f"\nMax input test TIMED OUT (exceeded {timeout_sec * 3}s)"
            except Exception as e:
                result_msg += f"\nMax input test error: {str(e)}"
        else:
            # Warn if no max-size test was provided
            result_msg += "\nWARNING: no max-size timing test was run"
        
        return f"ALL PASSED: {result_msg}"
        
    except Exception as e:
        return f"Fatal error in run_tests: {str(e)}"


if __name__ == "__main__":
    # Example usage
    print(tool_info())
